import { z } from 'zod';
import { ChargeKind, LedgerType, PaymentMethod } from '../enums.js';
import {
  idString,
  isoDate,
  money,
  optionalText,
  pagination,
  positiveMoney,
  queryBool,
  queryList,
} from '../primitives.js';

/*
 * Driver ledger. One table per driver across renewals; amounts are always positive and the
 * entry type gives the sign. Money rows are never edited or deleted: they are voided
 * (`POST /ledger/:id/void`), which is why there is no LedgerEntry update schema.
 */

/** Methods accepted for manual driver payments (TRADE_IN is deal-only, OFFSET is internal). */
export const LedgerPaymentMethod = PaymentMethod.exclude(['TRADE_IN', 'OFFSET']);
export type LedgerPaymentMethod = z.infer<typeof LedgerPaymentMethod>;

const attribution = {
  /** Contract the entry belongs to (optional for one-off charges). */
  contractId: idString.nullish(),
  /** Income attribution for P&L. */
  vehicleId: idString.nullish(),
  taxiLicenseId: idString.nullish(),
};

/** `POST /ledger/charges`. RENT charges are generated by billing, not created manually. */
export const LedgerChargeCreateSchema = z.object({
  driverId: idString,
  ...attribution,
  chargeKind: ChargeKind.exclude(['RENT']),
  date: isoDate,
  /** Defaults to `date`. */
  dueDate: isoDate.optional(),
  amount: positiveMoney,
  reference: optionalText(100),
  description: optionalText(500),
});
export type LedgerChargeCreate = z.infer<typeof LedgerChargeCreateSchema>;
export type LedgerChargeCreateInput = z.input<typeof LedgerChargeCreateSchema>;

/** `POST /ledger/payments` (prints an "payment confirmation", not a fiscal receipt). */
export const LedgerPaymentCreateSchema = z.object({
  driverId: idString,
  contractId: idString.nullish(),
  date: isoDate,
  amount: positiveMoney,
  method: LedgerPaymentMethod,
  /** Cheque number, transfer reference, Bit confirmation... */
  reference: optionalText(100),
  description: optionalText(500),
  /** Free-text note (stored as the entry description when `description` is not given). */
  notes: optionalText(500),
  /**
   * Charge ids to settle first, in this order (open charges of the same driver); whatever is
   * left is allocated FIFO. Kept on the entry so every re-allocation honours it.
   */
  allocateTo: z.array(idString).max(100).optional(),
});
export type LedgerPaymentCreate = z.infer<typeof LedgerPaymentCreateSchema>;
export type LedgerPaymentCreateInput = z.input<typeof LedgerPaymentCreateSchema>;

/** `POST /ledger/credits` (goodwill, unused days, corrections). */
export const LedgerCreditCreateSchema = z.object({
  driverId: idString,
  ...attribution,
  date: isoDate,
  amount: positiveMoney,
  reference: optionalText(100),
  description: optionalText(500),
});
export type LedgerCreditCreate = z.infer<typeof LedgerCreditCreateSchema>;
export type LedgerCreditCreateInput = z.input<typeof LedgerCreditCreateSchema>;

/** `POST /ledger/:id/void` */
export const LedgerVoidSchema = z.object({
  reason: z.string().trim().min(3).max(500),
});
export type LedgerVoid = z.infer<typeof LedgerVoidSchema>;

/** `GET /ledger?driverId&from&to&type` */
export const LedgerQuerySchema = pagination.extend({
  driverId: idString.optional(),
  contractId: idString.optional(),
  type: queryList(LedgerType).optional(),
  chargeKind: queryList(ChargeKind).optional(),
  from: isoDate.optional(),
  to: isoDate.optional(),
  includeVoided: queryBool.default(false),
});
export type LedgerQuery = z.infer<typeof LedgerQuerySchema>;

/** `GET /ledger/balances` (paginated; default order: balance, highest first). */
export const LedgerBalancesQuerySchema = pagination.extend({
  driverId: idString.optional(),
  /** Matches the driver's name. */
  q: z.string().trim().min(1).max(100).optional(),
  /** Only drivers who owe money (balance > 0). */
  debtorsOnly: queryBool.default(false),
  /** Only drivers with an open charge past its due date. */
  overdueOnly: queryBool.default(false),
});
export type LedgerBalancesQuery = z.infer<typeof LedgerBalancesQuerySchema>;

/** `GET /ledger/ageing` */
export const LedgerAgeingQuerySchema = z.object({
  driverId: idString.optional(),
  /** Ageing reference date (default: today). */
  asOf: isoDate.optional(),
});
export type LedgerAgeingQuery = z.infer<typeof LedgerAgeingQuerySchema>;

/** Row of the `driver_balance_v` view. `balance > 0` = the driver owes us. */
export const DriverBalanceSchema = z.object({
  driverId: idString,
  charged: money,
  paid: money,
  balance: money,
  depositHeld: money,
});
export type DriverBalance = z.infer<typeof DriverBalanceSchema>;

/** Row of the `driver_ageing_v` view (open charge amounts by days past due). */
export const DriverAgeingSchema = z.object({
  driverId: idString,
  current: money,
  days1to30: money,
  days31to60: money,
  days61to90: money,
  days90plus: money,
  total: money,
});
export type DriverAgeing = z.infer<typeof DriverAgeingSchema>;

/** `GET /drivers/:id/ledger?from&to&type&includeVoided` (statement, oldest first, no paging). */
export const DriverLedgerQuerySchema = z.object({
  from: isoDate.optional(),
  to: isoDate.optional(),
  type: queryList(LedgerType).optional(),
  includeVoided: queryBool.default(false),
});
export type DriverLedgerQuery = z.infer<typeof DriverLedgerQuerySchema>;

/**
 * Ageing bucket keys of the API responses (`ageing` on drivers, `GET /ledger/ageing` rows), in
 * display order: not yet due, 1-30, 31-60, 61-90 and over 90 days past due.
 */
export const LEDGER_AGEING_KEYS = ['current', 'd1_30', 'd31_60', 'd61_90', 'd90_plus'] as const;
export type LedgerAgeingKey = (typeof LEDGER_AGEING_KEYS)[number];

/** Ageing bucket keys in display order. */
export const AGEING_BUCKETS = [
  'current',
  'days1to30',
  'days31to60',
  'days61to90',
  'days90plus',
] as const;
export type AgeingBucket = (typeof AGEING_BUCKETS)[number];
