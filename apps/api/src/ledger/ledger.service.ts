  async createCharge(dto: LedgerChargeCreate, userId: string | null): Promise<LedgerEntryView> {
    await this.assertDriver(dto.driverId);
    const ctx = await this.attribution(dto.driverId, dto.contractId ?? null);
    const vehicleId = dto.vehicleId ?? ctx.vehicleId;
    const taxiLicenseId = dto.taxiLicenseId ?? ctx.taxiLicenseId;
    if (dto.vehicleId) await this.assertExists('vehicle', dto.vehicleId, 'vehicleId');
    if (dto.taxiLicenseId)
      await this.assertExists('taxiLicense', dto.taxiLicenseId, 'taxiLicenseId');
    const id = await this.prisma.$transaction(async (tx) => {
      const entry = await this.createEntry(tx, {
        driverId: dto.driverId,
        contractId: dto.contractId ?? null,
        type: 'CHARGE',
        chargeKind: dto.chargeKind,
        date: dto.date,
        dueDate: dto.dueDate ?? dto.date,
        amount: dto.amount,
        reference: dto.reference ?? null,
        description: dto.description ?? null,
        vehicleId,
        taxiLicenseId,
        userId,
      });
      await this.reallocateDriver(tx, dto.driverId);
      return entry.id;
    });
    return this.entryView(id);
  }

  async createPayment(dto: LedgerPaymentCreate, userId: string | null): Promise<LedgerEntryView> {
    await this.assertDriver(dto.driverId);
    await this.attribution(dto.driverId, dto.contractId ?? null);
    const allocateTo = [...new Set(dto.allocateTo ?? [])];
    if (allocateTo.length) {
      const found = await this.prisma.ledgerEntry.findMany({
        where: { id: { in: allocateTo }, driverId: dto.driverId, type: 'CHARGE', voidedAt: null },
        select: { id: true },
      });
      const ok = new Set(found.map((f) => f.id));
      const bad = (dto.allocateTo ?? []).findIndex((id) => !ok.has(id));
      if (bad >= 0) throw AppException.fieldError(`allocateTo.${bad}`, msg.invalidValue);
    }
    const id = await this.prisma.$transaction(async (tx) => {
      const entry = await this.createEntry(tx, {
        driverId: dto.driverId,
        contractId: dto.contractId ?? null,
        type: 'PAYMENT',
        date: dto.date,
        amount: dto.amount,
        method: dto.method,
        reference: dto.reference ?? null,
        description: dto.description ?? dto.notes ?? null,
        allocateTo,
        userId,
      });
      await this.reallocateDriver(tx, dto.driverId);
      return entry.id;
    });
    return this.entryView(id);
  }

