const SORTABLE_FIELDS = new Set(['date', 'dueDate', 'createdAt', 'amount', 'type']);

/** IANA zone names only (the value is interpolated into `SET LOCAL TIME ZONE`). */
const TZ_RE = /^[A-Za-z0-9_+\-/]+$/;

const numeric = z.custom<Prisma.Decimal>((v) => isDecimal(v));

/** `GET /ledger/balances` row (balance view + ageing view + driver name). */
const BalanceListRowSchema = z.object({
  driverId: z.string(),
  status: z.string(),
  firstName: z.string().nullable(),
  lastName: z.string().nullable(),
  companyName: z.string().nullable(),
  charged: numeric,
  paid: numeric,
  credited: numeric,
  balance: numeric,
  deposit_held: numeric,
  current: numeric,
  d1_30: numeric,
  d31_60: numeric,
  d61_90: numeric,
  d90_plus: numeric,
  total: numeric,
});

const AgeingListRowSchema = AgeingRowSchema.extend({
  firstName: z.string().nullable(),
  lastName: z.string().nullable(),
  companyName: z.string().nullable(),
});

export interface BalanceListItem {
  driverId: string;
  driver: NamedRef;
  status: string;
  charged: Prisma.Decimal;
  paid: Prisma.Decimal;
  credited: Prisma.Decimal;
  balance: Prisma.Decimal;
  depositHeld: Prisma.Decimal;
  /** Open amount past its due date. */
  overdue: Prisma.Decimal;
  ageing: AgeingView;
}

export interface AgeingListItem extends AgeingView {
  driverId: string;
  driver: NamedRef;
}

export interface LedgerList extends Paginated<LedgerEntryView> {
  /** Sums of the non-voided entries matching the filters (all pages). */
  totals: { charged: Prisma.Decimal; paid: Prisma.Decimal; credited: Prisma.Decimal };
}

export interface DriverStatement {
  /** Oldest first; `runningBalance` = balance after the entry (deposits do not move it). */
  items: StatementEntry[];
  /** Balance before `from` (0 without `from`). */
  openingBalance: Prisma.Decimal;
  /** Balance after the last entry up to `to`. */
  closingBalance: Prisma.Decimal;
  /** Current balance (all entries). */
  balance: Prisma.Decimal;
  depositHeld: Prisma.Decimal;
}

