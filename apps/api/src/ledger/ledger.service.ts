  async list(q: LedgerQuery): Promise<LedgerList> {
    let { from, to } = q;
    if (from && to && from > to) [from, to] = [to, from];
    const base: Prisma.LedgerEntryWhereInput = {
      ...(q.driverId ? { driverId: q.driverId } : {}),
      ...(q.contractId ? { contractId: q.contractId } : {}),
      ...(q.type?.length ? { type: { in: q.type } } : {}),
      ...(q.chargeKind?.length ? { chargeKind: { in: q.chargeKind } } : {}),
      ...(from || to
        ? { date: { gte: from ? dbDate(from) : undefined, lte: to ? dbDate(to) : undefined } }
        : {}),
    };
    const where: Prisma.LedgerEntryWhereInput = q.includeVoided
      ? base
      : { ...base, voidedAt: null };
    const sort = q.sort && SORTABLE_FIELDS.has(q.sort) ? q.sort : 'date';
    const orderBy: Prisma.LedgerEntryOrderByWithRelationInput[] = [
      sort === 'dueDate' ? { dueDate: { sort: q.order, nulls: 'last' } } : { [sort]: q.order },
      { createdAt: q.order },
      { id: 'asc' },
    ];
    const [total, rows, sums] = await this.prisma.$transaction([
      this.prisma.ledgerEntry.count({ where }),
      this.prisma.ledgerEntry.findMany({
        where,
        orderBy,
        skip: (q.page - 1) * q.pageSize,
        take: q.pageSize,
        include: ENTRY_INCLUDE,
      }),
      this.prisma.ledgerEntry.groupBy({
        by: ['type'],
        where: { ...base, voidedAt: null },
        orderBy: { type: 'asc' },
        _sum: { amount: true },
      }),
    ]);
    const sumOf = (type: LedgerEntry['type']) =>
      sums.find((s) => s.type === type)?._sum?.amount ?? ZERO;
    return {
      items: await this.toViews(rows),
      total,
      page: q.page,
      pageSize: q.pageSize,
      totals: { charged: sumOf('CHARGE'), paid: sumOf('PAYMENT'), credited: sumOf('CREDIT') },
    };
  }

  async entryView(id: string, tx: Tx = this.prisma): Promise<LedgerEntryView> {
    const row = await tx.ledgerEntry.findUnique({ where: { id }, include: ENTRY_INCLUDE });
    if (!row) throw AppException.notFound();
    const [view] = await this.toViews([row], tx);
    return view as LedgerEntryView;
  }

  /** Statement of one driver (`GET /drivers/:id/ledger`). */
  async statement(driverId: string, q: DriverLedgerQuery): Promise<DriverStatement> {
    let { from, to } = q;
    if (from && to && from > to) [from, to] = [to, from];
    const rows = await this.prisma.ledgerEntry.findMany({
      where: { driverId },
      include: ENTRY_INCLUDE,
      orderBy: [{ date: 'asc' }, { createdAt: 'asc' }, { id: 'asc' }],
    });
    const views = await this.toViews(rows);
    let running = ZERO;
    let opening = ZERO;
    let closing = ZERO;
    const items: StatementEntry[] = [];
    for (const v of views) {
      if (!v.voidedAt) running = running.plus(balanceEffect(v));
      const date = isoOf(v.date);
      if (from && date < from) {
        opening = running;
        closing = running;
        continue;
      }
      if (to && date > to) continue;
      closing = running;
      if (!q.includeVoided && v.voidedAt) continue;
      if (q.type?.length && !q.type.includes(v.type)) continue;
      items.push({ ...v, runningBalance: running });
    }
    const balance = await this.balanceOf(driverId);
    return {
      items,
      openingBalance: opening,
      closingBalance: closing,
      balance: balance.balance,
      depositHeld: balance.depositHeld,
    };
  }

  /** Charge id -> allocated amount (FIFO cache), plus remaining for each charge view. */
  async toViews(rows: EntryWithDriver[], tx: Tx = this.prisma): Promise<LedgerEntryView[]> {
    const chargeIds = rows.filter((r) => r.type === 'CHARGE').map((r) => r.id);
    const sums = chargeIds.length
      ? await tx.paymentAllocation.groupBy({
          by: ['chargeId'],
          where: { chargeId: { in: chargeIds } },
          orderBy: { chargeId: 'asc' },
          _sum: { amount: true },
        })
      : [];
    const allocatedById = new Map(sums.map((s) => [s.chargeId, s._sum?.amount ?? ZERO]));
    return rows.map(({ driver, ...entry }) => {
      const isCharge = entry.type === 'CHARGE';
      const allocated = isCharge ? (allocatedById.get(entry.id) ?? ZERO) : null;
      const remaining =
        isCharge && allocated
          ? entry.voidedAt
            ? ZERO
            : Prisma.Decimal.max(entry.amount.minus(allocated), ZERO)
          : null;
      return {
        ...entry,
        driver: { id: driver.id, name: contactDisplayName(driver.contact) },
        allocated,
        remaining,
      };
    });
  }

