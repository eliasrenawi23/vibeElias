  /**
   * Voids an entry (money rows are never edited or deleted). A deposit application is voided
   * together with its OFFSET payment (and vice versa).
   */
  async void(id: string, reason: string): Promise<LedgerEntryView> {
    const entry = await this.prisma.ledgerEntry.findUnique({ where: { id } });
    if (!entry) throw AppException.notFound();
    if (entry.voidedAt) throw AppException.conflict(ErrorKey.alreadyVoided);
    await this.prisma.$transaction(async (tx) => {
      const voidedAt = new Date();
      await tx.ledgerEntry.update({ where: { id }, data: { voidedAt, voidReason: reason } });
      const partnerType =
        entry.type === 'DEPOSIT_APPLIED'
          ? 'PAYMENT'
          : entry.type === 'PAYMENT' && entry.method === 'OFFSET'
            ? 'DEPOSIT_APPLIED'
            : null;
      if (partnerType && entry.reference) {
        await tx.ledgerEntry.updateMany({
          where: {
            id: entry.reference,
            driverId: entry.driverId,
            type: partnerType,
            voidedAt: null,
          },
          data: { voidedAt, voidReason: reason },
        });
      }
      await this.reallocateDriver(tx, entry.driverId);
    });
    return this.entryView(id);
  }

