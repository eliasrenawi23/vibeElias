import {
  ChargeKind,
  idString,
  isoDate,
  LedgerPaymentMethod,
  msg,
  optionalIsoDate,
  optionalText,
  positiveMoney,
  withParams,
} from '@renawi/shared';
import { z } from 'zod';

/** Contract a ledger entry can be attached to (driver-level dialogs offer a choice). */
export interface ContractOption {
  id: string;
  contractNo: number;
  /** Preselected (e.g. the active contract). */
  isDefault?: boolean;
}

const contractId = idString.nullish();

/** "Record payment" (`POST /ledger/payments`). */
export const PaymentFormSchema = z.object({
  contractId,
  amount: positiveMoney,
  date: isoDate,
  method: LedgerPaymentMethod,
  reference: optionalText(100),
  notes: optionalText(500),
});
export type PaymentFormInput = z.input<typeof PaymentFormSchema>;

/** Charge kinds that can be added by hand (rent is generated by billing). */
export const MANUAL_CHARGE_KINDS = ChargeKind.options.filter(
  (k): k is Exclude<ChargeKind, 'RENT'> => k !== 'RENT',
);

/** "Add charge" (`POST /ledger/charges`). */
export const ChargeFormSchema = z.object({
  contractId,
  chargeKind: ChargeKind.exclude(['RENT']),
  amount: positiveMoney,
  date: isoDate,
  dueDate: optionalIsoDate,
  description: optionalText(500),
});
export type ChargeFormInput = z.input<typeof ChargeFormSchema>;

/** "Add credit" (`POST /ledger/credits`): goodwill, unused days, corrections. */
export const CreditFormSchema = z.object({
  contractId,
  amount: positiveMoney,
  date: isoDate,
  description: optionalText(500),
});
export type CreditFormInput = z.input<typeof CreditFormSchema>;

/** "Void" (`POST /ledger/:id/void`). */
export const VoidFormSchema = z.object({
  reason: z
    .string()
    .trim()
    .min(3, { message: withParams(msg.minLength, { min: 3 }) })
    .max(500),
});

/** Default contract of a driver-level dialog: the given one, else the default option. */
export function defaultContractId(
  fixed: string | null | undefined,
  options: readonly ContractOption[] | undefined,
): string | null {
  if (fixed !== undefined) return fixed;
  return options?.find((o) => o.isDefault)?.id ?? null;
}
