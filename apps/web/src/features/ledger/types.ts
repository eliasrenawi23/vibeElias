import type { ChargeKind, LedgerType, PaymentMethod } from '@renawi/shared';
import type { NamedRef } from '../vehicles/types';

/**
 * One driver-ledger row as returned by the API. Amounts are positive; the type gives the sign
 * (CHARGE raises the balance, PAYMENT / CREDIT lower it, deposits sit outside the balance).
 */
export interface LedgerEntry {
  id: string;
  driverId: string;
  contractId: string | null;
  segmentId: string | null;
  type: LedgerType;
  chargeKind: ChargeKind | null;
  /** `YYYY-MM` of a RENT charge. */
  rentPeriod: string | null;
  date: string;
  dueDate: string | null;
  amount: number;
  method: PaymentMethod | null;
  reference: string | null;
  description: string | null;
  vehicleId: string | null;
  taxiLicenseId: string | null;
  autoGenerated: boolean;
  voidedAt: string | null;
  voidReason: string | null;
  /** Balance after this row (driver statement); computed here when the API omits it. */
  runningBalance?: number | null;
  /** Charges: amount covered by payments / credits (FIFO allocation). */
  allocated?: number | null;
  /** Charges: amount still open. */
  remaining?: number | null;
  /** `GET /ledger` items. */
  driver?: NamedRef | null;
  /** Contract number, when the API includes it. */
  contractNo?: number | null;
  /** Documents stored on the entry (generated deposit / payment confirmations). */
  documentCount?: number;
}

/** `GET /api/drivers/:id/ledger` */
export interface DriverLedger {
  /** Oldest to newest, each with `runningBalance`. */
  items: LedgerEntry[];
  balance: number;
  depositHeld: number;
}

/** `GET /api/ledger` (paged list plus totals). */
export interface LedgerList {
  items: LedgerEntry[];
  total?: number;
  page?: number;
  pageSize?: number;
  totals?: Partial<Record<'charged' | 'paid' | 'credited' | 'balance' | 'depositHeld', number>>;
}

/** Row of `GET /api/ledger/balances`. */
export interface DriverBalanceRow {
  driverId: string;
  name: string;
  charged: number;
  paid: number;
  credited: number;
  /** > 0: the driver owes us. */
  balance: number;
  depositHeld: number;
  current: number;
  d1_30: number;
  d31_60: number;
  d61_90: number;
  d90_plus: number;
}

/** Open charges by days past due. */
export interface Ageing {
  current: number;
  d1_30: number;
  d31_60: number;
  d61_90: number;
  d90_plus: number;
  total: number;
}

export const AGEING_KEYS = ['current', 'd1_30', 'd31_60', 'd61_90', 'd90_plus'] as const;
export type AgeingKey = (typeof AGEING_KEYS)[number];

/** Query of the ledger statements. */
export interface LedgerQuery {
  driverId?: string;
  contractId?: string;
  from?: string;
  to?: string;
  /** Comma-separated ledger types. */
  type?: string;
  includeVoided?: boolean;
}
