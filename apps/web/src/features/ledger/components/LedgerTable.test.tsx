import { act, fireEvent, screen, within } from '@testing-library/react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import i18n from '../../../app/i18n';
import { jsonResponse, renderWithProviders } from '../../../test/renderWithProviders';
import { withRunningBalance } from '../lib/ledger';
import type { LedgerEntry } from '../types';
import { LedgerTable } from './LedgerTable';

const jsdomMatchMedia = window.matchMedia;

beforeEach(async () => {
  await act(() => i18n.changeLanguage('en'));
  // A desktop viewport: every `min-width` breakpoint matches, so DataTable renders a table.
  window.matchMedia = (query: string) =>
    ({
      matches: query.includes('min-width'),
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList;
});

afterEach(() => {
  window.matchMedia = jsdomMatchMedia;
  vi.restoreAllMocks();
});

function entry(
  over: Partial<LedgerEntry> & Pick<LedgerEntry, 'id' | 'type' | 'amount' | 'date'>,
): LedgerEntry {
  return {
    driverId: 'drv_1',
    contractId: 'lc_1',
    segmentId: null,
    chargeKind: null,
    rentPeriod: null,
    dueDate: null,
    method: null,
    reference: null,
    description: null,
    vehicleId: null,
    taxiLicenseId: null,
    autoGenerated: false,
    voidedAt: null,
    voidReason: null,
    ...over,
  };
}

/** Oldest to newest: rent 1,500 -> payment 1,000 -> voided damage 200 -> credit 100 -> deposit in 5,000. */
const ITEMS: LedgerEntry[] = [
  entry({
    id: 'e1',
    type: 'CHARGE',
    chargeKind: 'RENT',
    rentPeriod: '2026-11',
    amount: 1500,
    date: '2026-11-01',
    dueDate: '2026-11-05',
    autoGenerated: true,
    allocated: 1100,
    remaining: 400,
  }),
  entry({
    id: 'e2',
    type: 'PAYMENT',
    amount: 1000,
    date: '2026-11-03',
    method: 'CASH',
    reference: 'R-77',
  }),
  entry({
    id: 'e3',
    type: 'CHARGE',
    chargeKind: 'DAMAGE',
    amount: 200,
    date: '2026-11-04',
    description: 'Mirror',
    voidedAt: '2026-11-05T10:00:00.000Z',
    voidReason: 'Charged twice',
  }),
  entry({ id: 'e4', type: 'CREDIT', amount: 100, date: '2026-11-06', description: 'Goodwill' }),
  entry({ id: 'e5', type: 'DEPOSIT_IN', amount: 5000, date: '2026-11-01', description: 'Deposit' }),
];

const row = (id: string) => {
  const el = document.querySelector<HTMLElement>(`tr[data-row-key="${id}"]`);
  if (!el) throw new Error(`row ${id} not rendered`);
  return el;
};
const balanceCell = (id: string) => {
  const cells = row(id).querySelectorAll('td');
  return cells[6] as HTMLElement;
};

describe('withRunningBalance', () => {
  it('computes the balance after each counted row (voided rows and deposits do not count)', () => {
    const rows = withRunningBalance(ITEMS);
    expect(rows.map((r) => r.balanceAfter)).toEqual([1500, 500, null, 400, 400]);
  });

  it('starts from an opening balance and avoids float drift', () => {
    const rows = withRunningBalance(
      [
        entry({ id: 'a', type: 'CHARGE', amount: 0.1, date: '2026-01-01' }),
        entry({ id: 'b', type: 'CHARGE', amount: 0.2, date: '2026-01-02' }),
      ],
      100,
    );
    expect(rows.map((r) => r.balanceAfter)).toEqual([100.1, 100.3]);
  });

  it("uses the API's runningBalance when every counted row carries it", () => {
    const rows = withRunningBalance([
      entry({ id: 'a', type: 'CHARGE', amount: 100, date: '2026-01-01', runningBalance: 2100 }),
      entry({ id: 'b', type: 'PAYMENT', amount: 50, date: '2026-01-02', runningBalance: 2050 }),
    ]);
    expect(rows.map((r) => r.balanceAfter)).toEqual([2100, 2050]);
  });
});

describe('LedgerTable', () => {
  it('renders charges, payments, the running balance and what is still open', async () => {
    renderWithProviders(<LedgerTable items={ITEMS} />);
    const table = await screen.findByTestId('ledger-table');

    // Rent charge: kind tag, month name of the rent period, charge column, balance, open amount.
    const rent = row('e1');
    expect(within(rent).getByText('Rent')).toBeInTheDocument();
    expect(within(rent).getByTestId('ledger-rent-period')).toHaveTextContent('November 2026');
    expect(rent).toHaveTextContent('₪1,500.00');
    expect(within(rent).getByTestId('ledger-remaining')).toHaveTextContent('₪400.00');
    expect(balanceCell('e1')).toHaveTextContent('₪1,500.00');
    expect(balanceCell('e1').querySelector('[data-balance]')).toHaveAttribute(
      'data-balance',
      'owes',
    );

    // Payment: method and reference, balance after it.
    expect(row('e2')).toHaveTextContent('Cash · R-77');
    expect(balanceCell('e2')).toHaveTextContent('₪500.00');

    // Credit lowers the balance; the deposit does not change it.
    expect(balanceCell('e4')).toHaveTextContent('₪400.00');
    expect(balanceCell('e5')).toHaveTextContent('₪400.00');
    expect(row('e5')).toHaveTextContent('Deposit received');

    // Amounts are LTR isolates.
    expect(table.querySelector('bdi.rm-money')).toHaveAttribute('dir', 'ltr');
  });

  it('strikes voided rows through and leaves them out of the balance', async () => {
    renderWithProviders(<LedgerTable items={ITEMS} />);
    await screen.findByTestId('ledger-table');
    const voided = row('e3');
    expect(voided).toHaveClass('rm-ledger-voided');
    expect(within(voided).getByTestId('ledger-voided-tag')).toHaveTextContent('Voided');
    expect(voided).toHaveTextContent('Void reason: Charged twice');
    // No running balance on the voided row, and none of the other rows count its 200.
    expect(balanceCell('e3')).toHaveTextContent('—');
    expect(row('e2')).not.toHaveClass('rm-ledger-voided');
    expect(balanceCell('e4')).toHaveTextContent('₪400.00');
  });

  it('offers "void" only on rows that are not voided yet', async () => {
    renderWithProviders(<LedgerTable items={ITEMS} onVoid={() => {}} />);
    await screen.findByTestId('ledger-table');
    expect(within(row('e1')).getByTestId('ledger-void')).toBeInTheDocument();
    expect(within(row('e3')).queryByTestId('ledger-void')).toBeNull();
  });
  it('shows a paperclip on rows with documents and lists them with open / download', async () => {
    const fetchMock = vi.spyOn(globalThis, 'fetch').mockImplementation(async () =>
      jsonResponse([
        {
          id: 'doc_1',
          kind: 'RECEIPT',
          fileName: 'payment-confirmation-2026-11-03.pdf',
          mime: 'application/pdf',
          size: 52_000,
          hasThumb: false,
          title: 'Payment confirmation',
          lang: 'en',
          expiresAt: null,
          createdAt: '2026-11-03T10:00:00.000Z',
          url: '/api/documents/doc_1/file',
        },
      ]),
    );
    const items = ITEMS.map((e) => (e.id === 'e2' ? { ...e, documentCount: 1 } : e));
    renderWithProviders(<LedgerTable items={items} pdfActions />);
    await screen.findByTestId('ledger-table');
    // Only the payment row has a document; the rent charge has none.
    expect(within(row('e1')).queryByTestId('ledger-documents')).toBeNull();
    const clip = within(row('e2')).getByTestId('ledger-documents');
    expect(clip).toHaveAttribute('aria-label', expect.stringContaining('Documents of this entry'));
    // Nothing is fetched before the click.
    expect(fetchMock).not.toHaveBeenCalled();

    fireEvent.click(clip);
    const list = await screen.findByTestId('ledger-documents-list');
    expect(String(fetchMock.mock.calls[0]?.[0])).toBe('/api/documents?ledgerEntryId=e2');
    expect(list).toHaveTextContent('Payment confirmation');
    expect(within(list).getByTestId('ledger-document-open')).toHaveAttribute(
      'href',
      '/api/documents/doc_1/file',
    );
    expect(within(list).getByTestId('ledger-document-download')).toHaveAttribute(
      'href',
      '/api/documents/doc_1/file?download=1',
    );
  });
});
